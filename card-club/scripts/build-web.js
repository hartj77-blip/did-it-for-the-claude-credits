// Builds the static GitHub Pages version into dist-web/.
// The game engine and room logic from server/ are bundled to run inside the
// host player's browser; friends connect to that browser over WebRTC (PeerJS).
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'dist-web');

// --- tiny CommonJS bundler: server/*.js + games, with `crypto` swapped for the shim ---
const ENTRY = 'server/(web-entry)';
const ENTRY_SRC = [
  "const { Rooms } = require('./rooms');",
  "const { createHandler } = require('./protocol');",
  'module.exports = { Rooms, createHandler };',
].join('\n');
const SHIMS = { crypto: 'web/crypto-shim.js' };
const modules = new Map(); // module id (repo-relative path) -> source

function resolve(fromFile, request) {
  if (SHIMS[request]) return SHIMS[request];
  if (!request.startsWith('.')) throw new Error(`Can't bundle "${request}" (required from ${fromFile})`);
  const p = path.posix.normalize(path.posix.join(path.posix.dirname(fromFile), request));
  return p.endsWith('.js') ? p : `${p}.js`;
}

function add(id, src = fs.readFileSync(path.join(ROOT, id), 'utf8')) {
  if (modules.has(id)) return;
  modules.set(id, null);
  modules.set(id, src.replace(/require\(\s*'([^']+)'\s*\)/g, (_, req) => {
    const target = resolve(id, req);
    add(target);
    return `__require(${JSON.stringify(target)})`;
  }));
}
add(ENTRY, ENTRY_SRC);

const bundle = [
  '// Card Club engine bundle (generated by scripts/build-web.js; do not edit).',
  '(function () {',
  '  const __defs = {};',
  '  const __cache = {};',
  '  function __require(id) {',
  '    if (__cache[id]) return __cache[id].exports;',
  '    const module = { exports: {} };',
  '    __cache[id] = module;',
  '    __defs[id](module, module.exports);',
  '    return module.exports;',
  '  }',
  ...[...modules].map(([id, src]) => `  __defs[${JSON.stringify(id)}] = function (module, exports) {\n${src}\n};`),
  `  window.CardClubEngine = __require(${JSON.stringify(ENTRY)});`,
  '})();',
  '',
].join('\n');

// --- assemble the site ---
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
for (const f of fs.readdirSync(path.join(ROOT, 'public'))) {
  if (f !== 'index.html') fs.copyFileSync(path.join(ROOT, 'public', f), path.join(OUT, f));
}
fs.writeFileSync(path.join(OUT, 'engine.js'), bundle);
fs.copyFileSync(path.join(ROOT, 'web', 'p2p.js'), path.join(OUT, 'p2p.js'));
fs.copyFileSync(require.resolve('peerjs/dist/peerjs.min.js'), path.join(OUT, 'peerjs.min.js'));

const html = fs.readFileSync(path.join(ROOT, 'public', 'index.html'), 'utf8').replace(
  '<script src="app.js"></script>',
  [
    '<script>window.CARD_CLUB_MODE = "p2p";</script>',
    '<script src="peerjs.min.js"></script>',
    '<script src="engine.js"></script>',
    '<script src="p2p.js"></script>',
    '<script src="app.js"></script>',
  ].join('\n  '),
);
if (!html.includes('CARD_CLUB_MODE')) throw new Error('index.html is missing the app.js script tag');
fs.writeFileSync(path.join(OUT, 'index.html'), html);
// Let GitHub Pages serve files as-is.
fs.writeFileSync(path.join(OUT, '.nojekyll'), '');

console.log(`Built ${path.relative(process.cwd(), OUT)}/ (${modules.size} engine modules)`);
